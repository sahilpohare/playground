// The rows each picked source holds, its row once when two of its groups share it
const picked = (paths: Parameters<Group["rows"]>[0]): Row[] => {
  const out = new Map<string, Row>()
  for (const [groups, whats] of PICKED)
    for (const group of groups)
      for (const row of group.rows(paths))
        if (whats.includes(row[0]) && !out.has(row[0])) out.set(row[0], row)
  return [...out.values()]
}

